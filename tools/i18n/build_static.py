#!/usr/bin/env python3
"""Build assets/js/i18n-static.js from static_en.json + static_hi.py.

static_en.json lists every static text block on the HTML pages (generated by
extract_static.js with Playwright). static_hi.py maps each block's index to its
Hindi HTML. At runtime app.js hashes each block's English text and swaps in the
Hindi version, so the HTML pages themselves stay in English.

Usage: python3 tools/i18n/build_static.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from static_hi import HI  # noqa: E402


def js_hash(s):
    """Same djb2 variant as SR.hash in app.js (over UTF-16 code units)."""
    h = 5381
    data = s.encode("utf-16-le")
    for i in range(0, len(data), 2):
        code = data[i] | (data[i + 1] << 8)
        h = ((h << 5) + h + code) & 0xFFFFFFFF
    out, digits = "", "0123456789abcdefghijklmnopqrstuvwxyz"
    if h == 0:
        return "0"
    while h:
        h, r = divmod(h, 36)
        out = digits[r] + out
    return out


def main():
    items = json.load(open(os.path.join(HERE, "static_en.json"), encoding="utf-8"))
    lines = ["/* Generated by tools/i18n/build_static.py — do not edit by hand.",
             "   Hindi versions of the static text on the HTML pages, keyed by a hash of the English text. */",
             "window.SR_HI_STATIC = {"]
    missing, seen = [], {}
    for i, it in enumerate(items):
        if i not in HI:
            missing.append(i)
            continue
        key = js_hash(it["text"])
        if key in seen:
            continue
        seen[key] = 1
        lines.append("  /* %s */" % it["text"][:90].replace("*/", "* /"))
        lines.append("  %s: %s," % (json.dumps(key), json.dumps(HI[i], ensure_ascii=False)))
    lines.append("};")
    open(os.path.join(ROOT, "assets/js/i18n-static.js"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("entries:", len(seen), "missing:", missing)


if __name__ == "__main__":
    main()
